"""Read-only author artifact checks; writes only critic evidence and manifest."""
import collections
import hashlib
import json
import platform
import re
import subprocess
import sys
import urllib.parse
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT).decode("utf-8").strip()


def main():
    changed = git("diff", "--name-only", "-z", "HEAD").split("\0")
    untracked = git("ls-files", "--others", "--exclude-standard", "-z").split("\0")
    files = sorted({p for p in changed + untracked if p})
    manifest_rel = "docs/verification/hw-v2-02d/manifest.json"
    output_rel = "docs/verification/hw-v2-02d/critic-final-checks.json"
    files = sorted(set(files + [output_rel]) - {manifest_rel})
    expected_generated = {ROOT / manifest_rel, ROOT / output_rel}
    assert all(p.endswith(".md") or not p.startswith("docs/reviews/")
               for p in files)
    missing, links = [], 0
    for rel in files:
        path = ROOT / rel
        if path.suffix != ".md":
            continue
        source = path.read_text(encoding="utf-8")
        for target in re.findall(r"\]\(([^\n]*?)\)", source):
            target = target.strip().split(' "', 1)[0].strip("<>")
            target = urllib.parse.unquote(target.split("#", 1)[0])
            if not target or re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target):
                continue
            resolved = (path.parent / target).resolve()
            links += 1
            if not resolved.exists() and resolved not in expected_generated:
                missing.append({"from": rel, "target": target})
    assert not missing, missing

    numerical = json.loads((HERE / "critic-check.json").read_text(encoding="utf-8"))
    calc = ROOT / "hardware/v2-input/p1-lv/calculations.json"
    assert digest(calc) == numerical["author_calculations_sha256"]
    assert len(numerical["comparisons"]) == 66
    evidence = json.loads((HERE / "guide-evidence.json").read_text(encoding="utf-8"))
    docx = ROOT / "docs/guides/motortester-input-guide-ru.docx"
    assert digest(docx) == evidence["docx_sha256"]
    render = ROOT / evidence["render_dir"]
    pages = list(render.glob("page-*.png"))
    assert len(pages) == 24
    assert {p.name: digest(p) for p in pages} == evidence["page_sha256"]
    previous = render.with_name("guide-render-02")
    changed_pages = sorted(p.name for p in pages if digest(p) != digest(previous / p.name))
    assert changed_pages == ["page-10.png", "page-7.png", "page-8.png"]
    source = ROOT / "docs/guides/input-explained-ru.md"
    images = re.findall(r"!\[[^\]]*\]\(([^)]+)\)", source.read_text(encoding="utf-8"))
    image_hashes = collections.Counter(digest((source.parent / p).resolve()) for p in images)
    with zipfile.ZipFile(docx) as z:
        embedded = [p for p in z.namelist() if p.startswith("word/media/")]
        embedded_hashes = collections.Counter(hashlib.sha256(z.read(p)).hexdigest() for p in embedded)
        xml = ET.fromstring(z.read("word/document.xml"))
    assert len(embedded) == 7 and embedded_hashes == image_hashes
    tables = len(xml.findall(".//{http://schemas.openxmlformats.org/wordprocessingml/2006/main}tbl"))
    assert tables == 12
    whitespace = subprocess.run(["git", "diff", "--check"], cwd=ROOT, capture_output=True, text=True)
    assert whitespace.returncode == 0, whitespace.stdout + whitespace.stderr
    report = {
        "status": "PASS_DOCUMENT_AND_ARTIFACT_CONSISTENCY",
        "python": sys.version.split()[0], "platform": platform.platform(),
        "base_commit": git("rev-parse", "HEAD"), "branch": git("branch", "--show-current"),
        "origin": git("remote", "get-url", "origin"),
        "local_file_links_checked": links, "missing_links": missing,
        "link_scope": "Markdown inline relative file targets in changed/new files; external URLs and anchors excluded",
        "author_calculations_sha256": digest(calc), "independent_comparisons": 66,
        "docx_sha256": digest(docx), "page_count": 24,
        "page_hashes_match_author_evidence": True,
        "changed_pages_from_render02": changed_pages,
        "images_embedded": 7, "image_hashes_match_sources": True, "tables": tables,
        "critic_visual_review": "render02 pages1-12; render03 pages13-24 and corrected7/8/10; other21 byte-identical. Final schematic/model-report PNGs inspected.",
        "git_diff_check": "PASS", "hardware_accessed": False,
        "limitations": ["File existence check excludes intra-document anchors and network link availability",
                        "Render generated by author; critic inspected pages and checked hashes, did not rerender",
                        "No hardware, firmware, GUI, CAD/ERC or physical qualification"]}
    (ROOT / output_rel).write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    entries = []
    for rel in files:
        payload = (ROOT / rel).read_bytes()
        entry = {"path": rel, "sha256": hashlib.sha256(payload).hexdigest()}
        if (ROOT / rel).suffix.lower() in {".md", ".py", ".svg", ".json", ".txt"}:
            entry["sha256_lf_normalized"] = hashlib.sha256(payload.replace(b"\r\n", b"\n")).hexdigest()
        entries.append(entry)
    manifest = {
        "schema": "hw-v2-02d-review-manifest-v1", "base_commit": report["base_commit"],
        "branch": report["branch"], "reviewed_at": "2026-10-21", "reviewer": "p1_r2_critic",
        "scope": "P1-LV r2 calculation, netlist/BOM, illustrations and explanatory Word; no hardware qualification",
        "verdict": "PASS", "score": 9.74,
        "criterion_scores": {"C1": 9.8, "C2": 9.7, "C3": 9.8, "C4": 9.6, "C5": 9.7},
        "hash_semantics": "sha256 exact working-tree bytes; sha256_lf_normalized replaces CRLF with LF for text checkout portability; manifest itself excluded",
        "unchanged_bases_at_base_commit": ["AGENTS.md", "docs/quality-gate.md", "docs/legacy-notice.md"],
        "verification": {"critic_check": "docs/verification/hw-v2-02d/critic-check.json",
                         "final_consistency_check": output_rel,
                         "review": "docs/reviews/hw-v2-02d-review.md",
                         "author_render_evidence": "docs/verification/hw-v2-02d/guide-evidence.json"},
        "files": entries}
    (ROOT / manifest_rel).write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({"status": report["status"], "files": len(entries), "local_file_links": links,
                      "pages": len(pages), "images": len(embedded), "score": manifest["score"]}))


if __name__ == "__main__":
    main()
