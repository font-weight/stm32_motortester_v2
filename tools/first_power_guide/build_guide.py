def table(y,headers,rows,widths,font=10):
    st=ParagraphStyle('cell',fontName='Body',fontSize=font,leading=font*1.25,textColor=HexColor(INK))
    data=[[Paragraph('<b>'+v+'</b>',st) for v in headers]]+[[Paragraph(v,st) for v in row] for row in rows]
    t=Table(data,colWidths=[v*mm for v in widths])
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),HexColor('#DDECF2')),
      ('ROWBACKGROUNDS',(0,1),(-1,-1),[white,HexColor('#F4F7F9')]),
      ('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),7),('RIGHTPADDING',(0,0),(-1,-1),7),
      ('TOPPADDING',(0,0),(-1,-1),6),('BOTTOMPADDING',(0,0),(-1,-1),6)]))
    _,h=t.wrap(174*mm,260*mm);assert y+h/mm<278,(y,h/mm)
    t.drawOn(C,18*mm,(297-y)*mm-h)
    TEXT.extend([' | '.join(headers)]+[' | '.join(r) for r in rows])
    return y+h/mm

