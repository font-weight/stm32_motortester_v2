TEXT_RECORD = []

def box(x,y,w,h,fill=LIGHT,stroke=None,r=2):
    C.setFillColor(HexColor(fill));C.setStrokeColor(HexColor(stroke or fill))
    C.setLineWidth(.3*mm)
    C.roundRect(x*mm,(297-y-h)*mm,w*mm,h*mm,r*mm,fill=1,stroke=bool(stroke))

def line(x1,y1,x2,y2,color=INK,width=.6,dash=None):
    C.setStrokeColor(HexColor(color));C.setLineWidth(width*mm)
    C.setDash(dash or [])
    C.line(x1*mm,(297-y1)*mm,x2*mm,(297-y2)*mm);C.setDash([])

def circle(x,y,r,fill,stroke=None):
    C.setFillColor(HexColor(fill));C.setStrokeColor(HexColor(stroke or fill))
    C.setLineWidth(.4*mm);C.circle(x*mm,(297-y)*mm,r*mm,fill=1,stroke=bool(stroke))

def label(x,y,t,size=10,color=INK,bold=False,align='left'):
    C.setFont('Bold' if bold else 'Body',size);C.setFillColor(HexColor(color))
    f = C.drawString if align=='left' else C.drawCentredString if align=='center' else C.drawRightString
    f(x*mm,(297-y)*mm,t);TEXT_RECORD.append(t)

def para(x,y,w,t,size=11.5,color=INK,bold=False,leading=None):
    st=ParagraphStyle('p',fontName='Bold' if bold else 'Body',fontSize=size,
        leading=leading or size*1.32,textColor=HexColor(color),spaceAfter=0)
    p=Paragraph(t,st);_,h=p.wrap(w*mm,260*mm)
    p.drawOn(C,x*mm,(297-y)*mm-h);TEXT_RECORD.append(t)
    return y+h/mm

def arrow(x1,y1,x2,y2,color=BLUE,width=.6):
    line(x1,y1,x2,y2,color,width)
    a=math.atan2(y2-y1,x2-x1)
    for da in [-.42,.42]:
        line(x2,y2,x2-2.6*math.cos(a+da),y2-2.6*math.sin(a+da),color,width)

def node(x,y,color=SIGNAL):circle(x,y,1.05,color)

def note(y,t,warm=False):
    st=ParagraphStyle('n',fontName='Body',fontSize=10.5,leading=14,textColor=HexColor(INK))
    p=Paragraph(t,st);_,h=p.wrap(166*mm,250*mm)
    box(18,y,174,h/mm+8,WARM if warm else LIGHT)
    p.drawOn(C,22*mm,(297-y-4)*mm-h);TEXT_RECORD.append(t)
    return y+h/mm+8

def step(y,n,title,t):
    circle(22,y+3,4.2,BLUE);label(22,y+4.3,str(n),11,'#FFFFFF',True,'center')
    end=para(30,y-1,160,'<b>'+title+'</b> '+t,11)
    return max(end,y+8)+4

def page(n,title,subtitle=None):
    if n>1:C.showPage()
    label(18,13,'МОТОРТЕСТЕР V2  /  ДАТЧИК P1',9,BLUE,True)
    label(192,13,'06.11.2026',9,MUTED,False,'right')
    y=para(18,22,174,title,23,bold=True,leading=26)
    if subtitle:y=para(18,y+3,174,subtitle,10.5,MUTED)
    label(18,286,'Сборка прототипа и низковольтная проверка',8.5,MUTED)
    label(192,286,f'{n} / 9',9,MUTED,False,'right')
    return y+8

def table(y,headers,rows,widths,font=10.5):
    st=ParagraphStyle('cell',fontName='Body',fontSize=font,leading=font*1.26,textColor=HexColor(INK))
    data=[[Paragraph('<b>'+v+'</b>',st) for v in headers]]
    data += [[Paragraph(str(v),st) for v in row] for row in rows]
    t=Table(data,colWidths=[v*mm for v in widths],hAlign='LEFT')
    t.setStyle(TableStyle([
        ('BACKGROUND',(0,0),(-1,0),HexColor('#DFECF2')),
        ('ROWBACKGROUNDS',(0,1),(-1,-1),[white,HexColor('#F4F7F9')]),
        ('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),7),
        ('RIGHTPADDING',(0,0),(-1,-1),7),('TOPPADDING',(0,0),(-1,-1),7),
        ('BOTTOMPADDING',(0,0),(-1,-1),7),
        ('LINEBELOW',(0,0),(-1,0),.5,HexColor(LINE)),
    ]))
    _,h=t.wrap(174*mm,260*mm)
    assert y+h/mm<277,(y,h/mm)
    t.drawOn(C,18*mm,(297-y)*mm-h)
    TEXT_RECORD.extend([' | '.join(headers)]+[' | '.join(map(str,r)) for r in rows])
    return y+h/mm

def cap(x,y1,y2,color=SIGNAL):
    m=(y1+y2)/2
    line(x,y1,x,m-1.5,color);line(x-4,m-1.5,x+4,m-1.5,color)
    line(x-4,m+1.5,x+4,m+1.5,color);line(x,m+1.5,x,y2,color)

def resistor(x,y1,y2,color=SIGNAL):
    m=(y1+y2)/2
    line(x,y1,x,m-6,color);box(x-2.5,m-6,5,12,'#FFFFFF',color,0)
    line(x,m+6,x,y2,color)

