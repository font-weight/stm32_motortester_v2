"""Build the concise Russian calibration guide from the current V2-17 workflow."""
from pathlib import Path
import re
from docx import Document
from docx.shared import Cm, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'готовые документы' / 'Калибровка CH1_пошаговая инструкция.docx'
doc = Document()
sec = doc.sections[0]
sec.page_width, sec.page_height = Cm(21), Cm(29.7)
sec.top_margin, sec.bottom_margin = Cm(1.65), Cm(1.65)
sec.left_margin, sec.right_margin = Cm(1.9), Cm(1.9)
sec.header_distance, sec.footer_distance = Cm(.7), Cm(.7)
for name in ('Normal', 'Title', 'Subtitle', 'Heading 1', 'Heading 2'):
    s = doc.styles[name]
    s.font.name = 'Calibri'
    s._element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), 'Calibri')
    s.font.color.rgb = RGBColor(0, 0, 0)
for style in doc.styles:
    for border in list(style.element.iter(qn('w:pBdr'))):
        border.getparent().remove(border)
doc.styles['Subtitle'].font.size = Pt(12)
doc.styles['Subtitle'].font.italic = False
normal = doc.styles['Normal']
normal.font.size = Pt(11)
normal.paragraph_format.space_after = Pt(5)
normal.paragraph_format.line_spacing = 1.05
doc.styles['Title'].font.size = Pt(23)
doc.styles['Title'].paragraph_format.space_after = Pt(8)
doc.styles['Heading 1'].font.size = Pt(17)
doc.styles['Heading 1'].paragraph_format.space_before = Pt(0)
doc.styles['Heading 1'].paragraph_format.space_after = Pt(9)
doc.styles['Heading 2'].font.size = Pt(12.5)
doc.styles['Heading 2'].paragraph_format.space_before = Pt(9)
doc.styles['Heading 2'].paragraph_format.space_after = Pt(4)

def para(text, style=None):
    p = doc.add_paragraph(style=style)
    for i, part in enumerate(re.split(r'\*\*(.*?)\*\*', text)):
        r = p.add_run(part)
        r.bold = bool(i % 2)
    p.paragraph_format.widow_control = True
    return p

def heading(text):
    return para(text, 'Heading 2')

def next_page(title):
    doc.add_page_break()
    para(title, 'Heading 1')

foot = sec.footer.paragraphs[0]
foot.alignment = WD_ALIGN_PARAGRAPH.RIGHT
run = foot.add_run('Мотортестер V2 · 14.11.2026   |   ')
run.font.size = Pt(9)
field = OxmlElement('w:fldSimple')
field.set(qn('w:instr'), 'PAGE')
foot._p.append(field)

para('Калибровка входа CH1', 'Title')
para('Пошаговая инструкция для Мотортестера V2', 'Subtitle')
para('Калибровка настраивает показания напряжения **на разъёме CH1**. Сначала выполняем DC + WIDE; для каждого режима AC нужна отдельная процедура. Названия кнопок приведены для интерфейса V2-17.')
para('**До начала:** аналоговая плата должна пройти первое включение и проверку перед подключением к PA0. Используйте инструкцию «Первое включение платы_R53.pdf» из той же папки. Датчик зажигания отключите. Если усилитель ещё не установлен, допустим только учебный опыт на странице 3.')

heading('1 Подготовьте соединения и режим')
para('Физически поставьте переключатели платы в **DC + WIDE**. Для ненулевого уровня подключайте плюс низковольтного источника к CH1, минус к AGND. Мультиметр включите на постоянное напряжение и подключите параллельно: красный щуп к CH1, чёрный к AGND.')
para('Подавайте только уровни в уже проверенном безопасном диапазоне платы. Записывайте **показание мультиметра на подключённом CH1**, а не цифру на экране источника.')

heading('2 Подготовьте приложение')
para('Выберите **COM6**, **«50 тыс. отсчётов/с · 12 бит»** и нажмите **«Подключить»**. Справа выберите **«DC + WIDE»**, раскройте **«Настройка входа»**, заполните **«Имя экземпляра платы»**, например «Моя R53 №1».')
para('Нажмите **«Расчётная шкала»**, подтвердите фактическое положение переключателей и нажмите **«Применить вход»**. Это начальная расчётная шкала, ещё не калибровка.')

heading('3 Запишите три отдельных уровня')
table = doc.add_table(rows=1, cols=2)
table.autofit = False
table.columns[0].width, table.columns[1].width = Cm(5.0), Cm(12.2)
for cell, text in zip(table.rows[0].cells, ['Имя новой записи', 'Что подключить к CH1']):
    cell.text = text
    for r in cell.paragraphs[0].runs:
        r.bold = True
for left, right in [
    ('DC_ноль.mtstream', 'Сначала отсоедините источник от CH1, затем соедините CH1 с AGND перемычкой.'),
    ('DC_верх.mtstream', 'Уберите перемычку. Подайте небольшой положительный уровень в проверенном диапазоне.'),
    ('DC_контроль.mtstream', 'Подайте другой уровень строго между первыми двумя, примерно посередине.')]:
    cells = table.add_row().cells
    cells[0].text, cells[1].text = left, right
for row in table.rows:
    trpr = row._tr.get_or_add_trPr()
    cant = OxmlElement('w:cantSplit'); trpr.append(cant)
    for cell in row.cells:
        tcpr = cell._tc.get_or_add_tcPr()
        margins = OxmlElement('w:tcMar')
        for edge in ('top', 'left', 'bottom', 'right'):
            el = OxmlElement('w:' + edge); el.set(qn('w:w'), '90'); el.set(qn('w:type'), 'dxa'); margins.append(el)
        tcpr.append(margins)
        borders = OxmlElement('w:tcBorders')
        for edge in ('top', 'left', 'bottom', 'right'):
            el = OxmlElement('w:' + edge); el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), '4'); el.set(qn('w:color'), 'D9D9D9'); borders.append(el)
        tcpr.append(borders)
        for p in cell.paragraphs:
            p.paragraph_format.space_after = Pt(2)
            for r in p.runs:
                r.font.size = Pt(10.5)
header_prop = table.rows[0]._tr.get_or_add_trPr()
header_prop.append(OxmlElement('w:tblHeader'))
for cell in table.rows[0].cells:
    shade = OxmlElement('w:shd'); shade.set(qn('w:fill'), 'F2F2F2')
    cell._tc.get_or_add_tcPr().append(shade)
para('Для каждого уровня дождитесь устойчивого показания мультиметра и запишите его. Нажмите **«Живой поток» → «Начать запись…»**, задайте новое имя файла, запишите **около 2 секунд**, затем нажмите **«Остановить»**. Перед следующей записью повторите шаг 2: то же имя платы, режим, частота и применение расчётной шкалы; после нового подключения заново подтвердите переключатели.')
para('Храните каждый файл **.mtstream вместе с .mtstream.v2.json**. Пауза просмотра не завершает запись. Для мастера нужна штатно остановленная запись без обрыва и явных потерь.')

next_page('Калибровка DC в мастере')
heading('4 Заполните условия опыта')
para('Справа нажмите **«Калибровка…»**. На странице **«1. Режим и условия опыта»** выберите:')
para('• **«Источник данных» — «Мои сохранённые записи STM32»**;\n• **«Физический режим» — «DC + WIDE»**;\n• **«Частота АЦП» — «50000 отсчётов/с · 12 сохранённых бит»**;\n• **«Экземпляр платы»** — ровно то имя, с которым записаны файлы.')
para('В **«Контрольный прибор»** укажите модель мультиметра и диапазон. В **«Условия»** — фактическое питание платы, маркировку усилителя, температуру, соединение земель и дату измерения.')
para('В **«Погрешность каждого опорного измерения, В»** введите абсолютную погрешность мультиметра в вольтах. Нужна наибольшая граница для трёх показаний на выбранном диапазоне; процент из паспорта нельзя просто вписать как вольты.')
para('В **«Допустимая ошибка с учётом погрешностей, В»** задайте заранее выбранный предел проверки. Если характеристики RM102 или требуемая точность пока неизвестны, остановитесь на учебном опыте: эти два числа нельзя придумывать или брать из учебных настроек.')

heading('5 Загрузите две исходные точки')
para('Нажмите **«Далее →»**. В группах **«Первый постоянный уровень»** и **«Второй постоянный уровень»** введите измеренные напряжения соответственно для нуля и верхнего уровня. Отметьте подтверждение измерения и нажмите **«Выбрать участок записи…»**.')
para('В окне выбора участка для каждого соответствующего файла:')
para('1) Нажмите **«Выбрать…»** и откройте запись.\n2) Укажите **«Начало участка, мс» — 1000**, **«Число отсчётов» — 12000**.\n3) Нажмите **«Показать исходный участок»**.\n4) Проверьте: уровень установился, нет скачков и упора в край диапазона кодов.\n5) Отметьте **«Участок установился, переходных процессов и ограничения не видно»**, затем **«Использовать участок»**.')
para('1000 мс — отступ от начала файла. 12000 отсчётов при выбранной частоте — участок длиной 240 мс. Если он не установился, выберите другой подходящий участок или повторите запись.')

heading('6 Проверьте независимый уровень и сохраните результат')
para('Нажмите **«Далее →»**. На странице **«3. Независимая проверка»** введите измеренное напряжение контрольного уровня и таким же способом загрузите DC_контроль.mtstream. Эта третья запись проверяет результат; коэффициенты по ней не подгоняются.')
para('Нажмите **«Далее →»**, затем **«Сохранить результат и исходные отсчёты…»**. Выберите новое имя файла **.mtcal.json**. Если контроль не пройден, сохраните неудачный опыт и выясните причину; не увеличивайте предел ошибки ради прохождения.')

heading('7 Примените принятую калибровку')
para('При результате **«Контроль пройден по введённым данным»** вернитесь в главное окно, подключите STM32 с той же частотой, но пока не запускайте поток. Выберите тот же режим и имя платы: **«Настройка входа» → «Загрузить калибровку…»** → ваш .mtcal.json. Подтвердите положение переключателей и нажмите **«Применить вход»**.')
para('Новая шкала используется графиком, курсорами и порогом. Прежние записи сохраняют собственную шкалу и исходные отсчёты. Другой режим, частота или экземпляр платы требуют своей калибровки.')

next_page('Отдельная калибровка AC')
para('Калибровку выполняют отдельно для **AC + WIDE** и **AC + SENSITIVE**. Постоянные напряжения и результат DC для этого не подходят: вход AC убирает постоянную составляющую.')
heading('1 Подготовьте источник переменного сигнала')
para('Нужны генератор синусоиды и прибор, который достоверно измеряет её амплитуду на выбранной частоте, например проверенный осциллограф. Не считайте показание RM102 верным на этой частоте без его характеристик. Измеряйте сигнал на подключённом CH1 относительно AGND.')
para('Амплитуды выбирайте в уже проверенном диапазоне платы, без ограничения сигнала. Физически выставьте нужный AC-режим и подтвердите его в **«Настройка входа»**. Во всех записях сохраняйте одинаковые частоту приёма, режим и имя платы.')

heading('2 Подготовьте три записи')
para('• **Ноль:** отсоедините источник, соедините CH1 с AGND и дождитесь установления.\n• **Известная синусоида:** уберите перемычку, подключите генератор, измерьте частоту и амплитуду на CH1.\n• **Контрольная синусоида:** отдельная запись с другой амплитудой на той же частоте.')
para('Сохраните каждую запись так же, как на странице 1, вместе с её .mtstream.v2.json. Для каждого опыта запишите фактическую амплитуду, частоту и погрешность контрольного прибора.')

heading('3 Пройдите мастер для выбранного AC режима')
para('В **«Калибровка…»** выберите **«Мои сохранённые записи STM32»** и нужный AC-режим. Заполните условия, погрешность и предел проверки. Укажите **«Частота синусоиды AC, Гц»** и тип поля **«Амплитуда AC»**: Vpp — размах от минимума до максимума; Vpk — пиковая амплитуда; Vrms — действующее значение. **Обе амплитуды, их погрешность и допустимую ошибку указывайте в выбранном виде**, например все в Vpp; не смешивайте его с Vrms.')
para('Укажите **«Знак передачи AC»** и заполните **«Как проверен знак AC»**. Знак проверяют отдельно сравнением входного и выходного сигналов с учётом фазового сдвига тракта; одно число амплитуды его не определяет. Если знак ещё не проверен, реальную калибровку не принимайте.')
para('На следующем шаге загрузите записи в **«Ноль · CH1 соединён с AGND»** и **«Известная синусоида»**. Затем используйте третью запись на странице **«3. Независимая проверка»**.')
para('В выбранном участке синусоиды должно быть **не менее 10 периодов и 10 отсчётов на период**. Например, 12000 отсчётов подходят для 1 кГц при текущих частотах приёма. Это пример длины участка, а не подтверждение точности мультиметра на 1 кГц.')
para('Сохраните результат. После успешного контроля примените его по шагу 7 на странице 2, выбрав соответствующий AC-режим. Для второго AC-режима повторите процедуру. Проверка относится к испытанным частоте и амплитудам, а не ко всей полосе.')

heading('Если плата ещё не готова')
para('Можно освоить мастер без подключения: выберите **«Учебный опыт · искусственные данные»**, затем **«Далее →»**. Для двух исходных точек нажмите **«Создать учебные отсчёты»**; повторите это на независимой проверке и сохраните результат. Такой файл нельзя применять как калибровку реального прибора.')
para('**Предел результата:** в AC показывается переменная составляющая напряжения CH1. Калибровка не подтверждает защиту входа, допустимое высокое напряжение или готовность к автомобилю; пересчёта в киловольты зажигания нет.')

doc.core_properties.title = 'Калибровка входа CH1'
doc.core_properties.subject = 'Пошаговая инструкция DC WIDE и AC для интерфейса V2-17'
doc.core_properties.author = 'Мотортестер V2'
OUT.parent.mkdir(parents=True, exist_ok=True)
doc.save(OUT)
print(OUT)
